#!/usr/bin/env node
/* D7: the experience summary.

   This site has no build step, and the rule that matters most here is that
   every page renders with JavaScript off. So the section is GENERATED INTO
   index.html between two markers rather than rendered in the browser: the
   dates are the thing a recruiter scans for in sixty seconds and they must
   be in the HTML a crawler and a slow phone both receive.

   Run after editing content/experience.json:
     node tools/build-experience.js
     node tools/build-experience.js --check   (report only, writes nothing)

   The section is omitted entirely while no row is published. It never
   ships as a stub: an experience summary with {{TITLE}} in it would be
   worse than none, which is the honesty rule this repo already runs on. */

const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const CHECK = process.argv.includes('--check');

const START = '<!-- EXPERIENCE:START  generated by tools/build-experience.js, do not edit by hand -->';
const END = '<!-- EXPERIENCE:END -->';

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/* "2024-03" -> "Mar 2024"; "Present" passes through */
function human(v) {
  if (!v || /present/i.test(v)) return 'Present';
  const m = /^(\d{4})-(\d{2})$/.exec(v.trim());
  if (!m) return esc(v);
  const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  return MONTHS[+m[2] - 1] + ' ' + m[1];
}

let data;
try { data = JSON.parse(fs.readFileSync(path.join(ROOT, 'content', 'experience.json'), 'utf8')); }
catch (e) { console.log('content/experience.json missing or invalid: ' + e.message); process.exit(1); }

const all = data.roles || [];
const problems = [];
const live = all.filter(r => {
  if (r.published !== true) return false;
  const raw = JSON.stringify(r);
  if (/\{\{/.test(raw)) { problems.push(`${r.org || '(no org)'}: published:true but still has a placeholder`); return false; }
  for (const f of ['title', 'org', 'from', 'to', 'line']) {
    if (!r[f]) { problems.push(`${r.org || '(no org)'}: missing "${f}"`); return false; }
  }
  if (r.line.length > 120) problems.push(`${r.org}: line is ${r.line.length} chars, max 120`);
  return true;
});

console.log(`experience: ${all.length} roles, ${live.length} publishable, ${all.length - live.length} waiting`);
problems.forEach(p => console.log('  ! ' + p));

const block = live.length ? `${START}
<section class="xp" aria-labelledby="xp-title">
  <div class="wrap">
    <div class="shead rv"><img class="smark" src="assets/star.webp" alt=""><span class="no">02 / Experience</span><h2 id="xp-title">Where this was learnt</h2></div>
    <ol class="xp-list">
${live.map(r => `      <li class="xp-row">
        <span class="xp-title">${esc(r.title)}</span>
        <span class="xp-org">${esc(r.org)}</span>
        <span class="xp-when mono"><time datetime="${esc(r.from)}">${human(r.from)}</time> &ndash; <time datetime="${esc(r.to)}">${human(r.to)}</time></span>
        <span class="xp-line">${esc(r.line)}</span>
      </li>`).join('\n')}
    </ol>
  </div>
</section>
${END}` : `${START}
${END}`;

const p = path.join(ROOT, 'index.html');
const raw = fs.readFileSync(p, 'utf8');
const crlf = /\r\n/.test(raw);
let h = raw.replace(/\r\n/g, '\n');

const s = h.indexOf(START);
const e = h.indexOf(END);
if (s < 0 || e < 0) { console.log('markers not found in index.html; add them once and re-run'); process.exit(1); }

const next = h.slice(0, s) + block + h.slice(e + END.length);
if (CHECK) { console.log(next === h ? 'index.html is up to date' : 'index.html would change'); process.exit(0); }
if (next === h) { console.log('index.html already up to date'); process.exit(0); }
fs.writeFileSync(p, crlf ? next.replace(/\n/g, '\r\n') : next);
console.log(live.length ? 'index.html: experience section written' : 'index.html: experience section omitted (nothing published)');
