/* =========================================================================
   tools/audit.mjs — Baseline System v1, B1
   Run:  npm run audit        (or: node tools/audit.mjs)
         npm run audit -- --open     also writes /audit/*.png
   Exits 1 on any FAIL. A task is not done until this passes.

   WHY NOT PLAYWRIGHT, WHICH IS WHAT HE ASKED FOR. This repo has no
   package.json, no node_modules and no build step - commit d5aa99b
   stripped the toolchain on purpose to collapse three parallel
   realities into one, and CLAUDE.md records that as a standing rule
   with exactly one exception (the Tailwind standalone binary).
   Playwright is a ~200MB install plus a browser download to do what
   headless Chrome over CDP already does here, with harnesses that have
   found real bugs in this repo for a month. So: same checks, same three
   widths, same screenshots, zero dependencies. `npm run audit` works
   literally because package.json has a script and nothing else.

   If he wants Playwright specifically, it is a drop-in: the checks are
   all in ONE page-evaluated function (CHECKS) that takes a document and
   returns findings. Any driver can run it.
   ========================================================================= */
import { spawn } from 'node:child_process';
import { mkdtempSync, writeFileSync, mkdirSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const WIDTHS = [375, 768, 1280];
const SHOTS = process.argv.includes('--open');

/* ---- the pages: every html file that is actually routed ---- */
function pages(dir = ROOT, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (['.git', '_archive', 'node_modules', 'audit', 'references', '.tools'].includes(e.name)) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) pages(p, out);
    else if (e.name.endsWith('.html') && e.name !== '404.html') out.push(p);
  }
  return out;
}

/* =========================================================================
   PART 1 — the source lint (Principle 0)
   No raw hex, no px font-size, no inline transform outside design/.
   ========================================================================= */
function lintSources() {
  const fails = [];
  const allow = [join(ROOT, 'design'), join(ROOT, 'assets', 'vendor'), join(ROOT, 'tools')];
  const isAllowed = f => allow.some(a => f.startsWith(a));

  function walk(dir, out = []) {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (['.git', '_archive', 'node_modules', 'audit', 'references', '.tools', 'public'].includes(e.name)) continue;
      const p = join(dir, e.name);
      if (e.isDirectory()) walk(p, out);
      else if (/\.(css|html)$/.test(e.name)) out.push(p);
    }
    return out;
  }

  for (const f of walk(ROOT)) {
    if (isAllowed(f)) continue;
    const rel = relative(ROOT, f).replace(/\\/g, '/');
    /* tw.css is generated by the Tailwind binary and is not hand-authored;
       404.html is the documented inline-style exception. */
    if (rel === 'assets/tw.css' || rel === '404.html') continue;
    const src = readFileSync(f, 'utf8');
    const noComments = src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/<!--[\s\S]*?-->/g, '');

    const hex = [...noComments.matchAll(/#[0-9a-fA-F]{3,8}\b/g)]
      .map(m => m[0]).filter(h => !/^#[0-9a-fA-F]{0,2}$/.test(h));
    if (hex.length) fails.push({ file: rel, rule: 'raw hex', n: hex.length, eg: [...new Set(hex)].slice(0, 5).join(' ') });

    const pxFont = [...noComments.matchAll(/font-size\s*:\s*[^;}]*?\d+(?:\.\d+)?px/g)].map(m => m[0].trim());
    if (pxFont.length) fails.push({ file: rel, rule: 'px font-size', n: pxFont.length, eg: [...new Set(pxFont)].slice(0, 3).join(' | ') });

    const inlineT = [...noComments.matchAll(/style\s*=\s*"[^"]*transform\s*:/g)].map(m => m[0]);
    if (inlineT.length) fails.push({ file: rel, rule: 'inline transform', n: inlineT.length, eg: inlineT[0].slice(0, 40) });
  }
  return fails;
}

/* =========================================================================
   PART 2 — the rendered checks, run inside the page
   ========================================================================= */
const CHECKS = `(() => {
  const F = [], N = [];
  const nm = e => (e.tagName.toLowerCase() + (e.className ? '.' + String(e.className).trim().split(/\\s+/)[0] : '')).slice(0,34);
  const vis = e => { const r = e.getBoundingClientRect(); const g = getComputedStyle(e);
    return r.width > 0 && r.height > 0 && g.visibility !== 'hidden' && g.display !== 'none' && g.opacity !== '0'; };

  /* 1. h2 left edges. Screen-reader-only headings are a 1x1 clipped box:
        their x is meaningless, and counting it is a standing false
        positive this repo already had to teach a harness to skip. */
  const h2 = [...document.querySelectorAll('h2')].filter(e => {
    const r = e.getBoundingClientRect();
    return r.height > 2 && r.width > 2 && !e.classList.contains('vh');
  });
  const xs = [...new Set(h2.map(e => Math.round(e.getBoundingClientRect().left)))];
  if (xs.length > 1) {
    /* name the MINORITY, not whatever happened to be first in document
       order: the first cut printed the four headings that were correct
       and hid the one that was not. */
    const count = {};
    h2.forEach(e => { const x = Math.round(e.getBoundingClientRect().left); count[x] = (count[x]||0)+1; });
    const main = +Object.entries(count).sort((a,b)=>b[1]-a[1])[0][0];
    F.push('h2 left edges: ' + xs.length + ' -> ' + xs.join(', ') + '  | majority ' + main +
      ', off: ' + h2.filter(e => Math.round(e.getBoundingClientRect().left) !== main)
        .map(e => nm(e) + '@' + Math.round(e.getBoundingClientRect().left) +
          ' "' + e.textContent.trim().slice(0,22) + '"').join(', '));
  }
  else N.push('h2 left edge: 1 (' + (xs[0] ?? '-') + 'px), ' + h2.length + ' headings');

  /* 2. tilt angles on non-stickers. A sticker is decoration: aria-hidden,
        or one of the named artefacts. Everything else is content. */
  const STICKER = '.sign-star,.ground-star,.smark,.tile,.so-card,.mot-item,.p-is,.p-mark,.sticker,.pm,.strip-head,.hero-pola,.ww-mark';
  const angles = new Set();
  document.querySelectorAll('*').forEach(e => {
    if (!vis(e)) return;
    const m = (getComputedStyle(e).transform || '').match(/matrix\\(([^)]+)\\)/);
    if (!m) return;
    const [a,b] = m[1].split(',').map(Number);
    const deg = Math.round(Math.atan2(b,a) * 180 / Math.PI * 10) / 10;
    if (!deg) return;
    if (e.matches(STICKER) || e.closest(STICKER) || e.closest('[aria-hidden="true"]')) return;
    angles.add(deg);
  });
  if (angles.size > 3) F.push('tilt angles on non-stickers: ' + angles.size + ' -> ' + [...angles].join(', '));
  else N.push('tilt angles on non-stickers: ' + angles.size + (angles.size ? ' (' + [...angles].join(', ') + ')' : ''));

  /* 3. outline weights */
  const w = {};
  document.querySelectorAll('*').forEach(e => {
    if (!vis(e)) return;
    /* HIS TOKENS ALLOW 2.4px ON HOVER AND ACTIVE, so an element in one of
       those states is not a second weight - it is the one weight doing
       what the spec says. On a real page nothing is hovered when the
       audit runs; on the styleguide the forced-state demos are, and
       counting them reported the system contradicting itself. */
    if (e.matches(':hover,:active') || /\\bsg-(hover|active)\\b/.test(e.className)) return;
    const g = getComputedStyle(e);
    ['Top','Right','Bottom','Left'].forEach(s => {
      const v = parseFloat(g['border'+s+'Width']);
      if (v > 0 && g['border'+s+'Style'] !== 'none') w[v] = (w[v]||0)+1;
    });
  });
  const ws = Object.keys(w).map(Number).sort((a,b)=>a-b);
  if (ws.length > 1) F.push('outline weights: ' + ws.map(v=>v+'px x'+w[v]).join(', '));
  else N.push('outline weight: ' + ws.map(v=>v+'px x'+w[v]).join('') + ' (1.6px declared; Chrome snaps to the device pixel)');

  /* 4. font sizes and 5. families */
  const sz = {}, fam = {};
  document.querySelectorAll('*').forEach(e => {
    if (![...e.childNodes].some(n => n.nodeType === 3 && n.textContent.trim())) return;
    if (!vis(e) || e.closest('.vh')) return;
    const g = getComputedStyle(e);
    const s = Math.round(parseFloat(g.fontSize));
    (sz[s] = sz[s] || []).push(nm(e));
    fam[g.fontFamily.split(',')[0].replace(/["']/g,'').trim()] = 1;
  });
  /* .bigmark is a drawn shape made of letters, not type on a scale */
  const sizes = Object.keys(sz).map(Number).sort((a,b)=>a-b)
    .filter(s => !sz[s].every(n => n.indexOf('bigmark') >= 0));
  if (sizes.length > 5) F.push('font sizes: ' + sizes.length + ' -> ' + sizes.join(', ') +
    '  | off-scale: ' + sizes.filter(s=>![12,16,20,32,56].includes(s))
      .map(s=>s+'px on '+[...new Set(sz[s])].slice(0,3).join(',')).join(' ; '));
  else N.push('font sizes: ' + sizes.join(', '));
  const fams = Object.keys(fam);
  if (fams.length > 3) F.push('font families: ' + fams.length + ' -> ' + fams.join(', '));
  else N.push('font families: ' + fams.join(', '));

  /* 6. horizontal scroll */
  const ov = document.documentElement.scrollWidth - document.documentElement.clientWidth;
  if (ov > 0) F.push('horizontal scroll: ' + ov + 'px'); else N.push('no horizontal scroll');

  /* 7. sibling boxes overlapping. Only TEXT-BEARING siblings under one
        parent: a grid column beside another is not an overlap, and an
        absolutely positioned decoration over a block is the design. */
  let hits = 0, eg = [];
  document.querySelectorAll('*').forEach(p => {
    const kids = [...p.children].filter(c => {
      if (!vis(c)) return false;
      const g = getComputedStyle(c);
      if (g.position !== 'static') return false;
      /* AN INLINE BOX THAT WRAPS IS NOT AN OVERLAP. getBoundingClientRect
         on a wrapped inline returns the UNION of its line fragments, so
         two spans on different lines of the same paragraph report boxes
         that cross. The word-by-word ink wraps every word in a span, so
         this produced 36 phantom overlaps on home at 768 before the
         filter. Block-level siblings only; an inline is measured by its
         fragments or not at all. */
      if (g.display.startsWith('inline') && g.display !== 'inline-block') return false;
      return [...c.childNodes].some(n => n.nodeType === 3 && n.textContent.trim());
    });
    for (let i=0;i<kids.length;i++) for (let j=i+1;j<kids.length;j++) {
      const a = kids[i].getBoundingClientRect(), b = kids[j].getBoundingClientRect();
      const dx = Math.max(a.left-b.right, b.left-a.right), dy = Math.max(a.top-b.bottom, b.top-a.bottom);
      if (dx < -1 && dy < -1) { hits++; if (eg.length<3) eg.push(nm(kids[i])+' x '+nm(kids[j])); }
    }
  });
  if (hits) F.push('overlapping sibling text boxes: ' + hits + ' -> ' + eg.join(', '));
  else N.push('no overlapping sibling text boxes');

  /* 8. tap targets. An element whose own box is small but which sits
        inside a 44px row is reachable; this measures the control. */
  const small = [];
  document.querySelectorAll('a,button,input,select,summary,[role=button]').forEach(e => {
    if (!vis(e) || e.closest('.vh')) return;
    const r = e.getBoundingClientRect();
    if (r.height < 44 || r.width < 24) small.push(nm(e) + ' ' + Math.round(r.width) + 'x' + Math.round(r.height));
  });
  if (small.length) F.push('tap targets under 44px tall: ' + small.length + ' -> ' + [...new Set(small)].slice(0,6).join(', '));
  else N.push('all tap targets at least 44px tall');

  /* 9. placeholder text */
  /* THE STYLEGUIDE IS EXEMPT FROM THIS ONE RULE, and only this one. It
     is a noindex dev page whose whole job is to DOCUMENT the rules, so
     it says "never TBC" and shows a row labelled "being written" as the
     not-linked state. The rule is about production copy; contorting the
     documentation to dodge its own vocabulary would make the styleguide
     worse at the thing it exists for. Every other check still runs here. */
  const isStyleguide = location.pathname.indexOf('/styleguide/') >= 0;
  const t = document.body.innerText;
  const bad = isStyleguide ? []
    : ['[GAP','{{','TBC','to be confirmed','being written']
        .filter(s => new RegExp(s.replace(/[.*+?^\${}()|[\\]\\\\]/g,'\\\\$&'),'i').test(t));
  if (bad.length) F.push('placeholder text on the page: ' + bad.join(', '));
  else N.push(isStyleguide ? 'placeholder check skipped (styleguide documents the rule)' : 'no placeholder text');

  /* 10. images without alt */
  const noAlt = [...document.querySelectorAll('img')].filter(i => !i.hasAttribute('alt'));
  if (noAlt.length) F.push('images with no alt attribute: ' + noAlt.length);
  else N.push('every image has an alt attribute');

  return { F, N };
})()`;

