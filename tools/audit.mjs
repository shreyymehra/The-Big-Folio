const chrome = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const port = 9300 + Math.floor(Math.random() * 500);
const prof = mkdtempSync(join(tmpdir(), 'audit-'));
const proc = spawn(chrome, ['--headless=new', `--remote-debugging-port=${port}`, `--user-data-dir=${prof}`,
  '--hide-scrollbars', '--no-first-run', '--disable-gpu', 'about:blank'], { stdio: 'ignore' });
const sleep = ms => new Promise(r => setTimeout(r, ms));
let target;
for (let i = 0; i < 80 && !target; i++) {
  try { const l = await (await fetch(`http://127.0.0.1:${port}/json`)).json(); target = l.find(t => t.type === 'page'); } catch {}
  if (!target) await sleep(200);
}
if (!target) { console.error('could not start headless Chrome'); process.exit(1); }
const ws = new WebSocket(target.webSocketDebuggerUrl); await new Promise(r => ws.onopen = r);
let id = 0; const pend = {}; let consoleErrors = [];
ws.onmessage = e => {
  const m = JSON.parse(e.data);
  if (m.id && pend[m.id]) { pend[m.id](m); delete pend[m.id]; return; }
  if (m.method === 'Runtime.exceptionThrown') consoleErrors.push('EXC ' +
    (m.params.exceptionDetails.exception?.description || m.params.exceptionDetails.text || '').split('\n')[0]);
  if (m.method === 'Runtime.consoleAPICalled' && m.params.type === 'error')
    consoleErrors.push('ERR ' + m.params.args.map(a => a.value ?? a.description ?? '').join(' ').slice(0, 120));
};
const send = (m, p = {}) => new Promise(r => { const i = ++id; pend[i] = r; ws.send(JSON.stringify({ id: i, method: m, params: p })); });
const ev = async x => (await send('Runtime.evaluate', { expression: x, awaitPromise: true, returnByValue: true })).result?.result?.value;

await send('Runtime.enable');
await send('Page.enable');
if (SHOTS) mkdirSync(join(ROOT, 'audit'), { recursive: true });

const PAGES = pages();
let failCount = 0;
const report = [];

/* the source lint runs once, not per width */
const lint = lintSources();
report.push('SOURCE LINT (Principle 0: no raw hex, px font-size or inline transform outside design/)');
if (!lint.length) report.push('  pass');
else lint.forEach(l => { failCount++; report.push('  FAIL ' + l.file + '  ' + l.rule + ' x' + l.n + '  e.g. ' + l.eg); });
report.push('');

for (const file of PAGES) {
  const rel = relative(ROOT, file).replace(/\\/g, '/');
  const url = 'file:///' + file.replace(/\\/g, '/').replace(/ /g, '%20');
  for (const w of WIDTHS) {
    consoleErrors = [];
    await send('Emulation.setDeviceMetricsOverride', { width: w, height: 900, deviceScaleFactor: 1, mobile: w < 700 });
    await send('Page.navigate', { url });
    await sleep(1500);
    await ev(`(async()=>{await document.fonts.ready;const l=document.getElementById('loader');if(l)l.remove();return 1})()`);
    await sleep(400);
    const r = await ev(CHECKS);
    const F = (r?.F || []).concat(consoleErrors.length ? ['console errors: ' + consoleErrors.slice(0, 3).join(' | ')] : []);
    report.push(rel + '  @' + w + (F.length ? '   ' + F.length + ' FAIL' : '   pass'));
    F.forEach(f => { failCount++; report.push('    FAIL ' + f); });
    if (SHOTS) {
      const shot = await send('Page.captureScreenshot', { format: 'png' });
      writeFileSync(join(ROOT, 'audit', rel.replace(/[\/]/g, '_').replace('.html', '') + '-' + w + '.png'),
        Buffer.from(shot.result.data, 'base64'));
    }
  }
}

/* unfilled asset slots, per the throw-back protocol */
let slots = 0;
try {
  const reqs = JSON.parse(readFileSync(join(ROOT, 'assets', 'ASSET_REQUESTS.json'), 'utf8'));
  slots = (reqs.requests || []).filter(r => r.status !== 'approved').length;
} catch (e) { /* no register yet */ }

console.log(report.join('\n'));
console.log('\n' + slots + ' slots unfilled');
console.log(failCount ? '\nAUDIT FAILED: ' + failCount + ' finding(s)' : '\nAUDIT PASSED');
if (SHOTS) console.log('screenshots in /audit/');
ws.close(); proc.kill();
process.exit(failCount ? 1 : 0);
