#!/usr/bin/env node
/* Draw the running stitch once, with a seeded random, into
 * assets/img/stitch.svg.  Run:  node tools/build-stitch.js
 *
 * WHY A FILE AND NOT CSS. The divider was two repeating-linear-gradients,
 * which cannot do any of what his brief asks for: a gradient cannot rotate
 * an individual stitch, cannot wobble its baseline, cannot back-stitch and
 * cannot tie a knot. It can only repeat, and a thing that repeats exactly
 * is the dashed form-field border the stitch exists to not be.
 *
 * WHY 2560 WIDE AND NOT A SMALL REPEATING TILE. A tile repeats, and the eye
 * finds the period immediately on a line this thin - which is the same bug
 * the cloud band had in October, a hard join every 720px. One pass wider
 * than any viewport means no period to find. It is ~20KB of path data, which
 * is cheaper than the two 1500px rasters this repo has already had to resize.
 *
 * THE SEED IS FIXED, so the stitching is identical on every build, every
 * page and every reader. Change SEED and every stitch moves.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

const SEED = 20261028;
const W = 2560;          /* one pass, wider than any viewport */
const H = 14;            /* the height .stitch already reserves */
const BASE = 8;          /* the thread's resting line */

/* his numbers, verbatim */
const LEN = 9, LEN_J = 1.5;      /* stitch length 9px +-1.5  */
const GAP = 6, GAP_J = 1;        /* gap 6px +-1              */
const ANG = 3;                   /* angle +-3 degrees        */
const YOFF = 0.8;                /* y-offset +-0.8px         */
const AMP = 1.5;                 /* path wobble amplitude    */
const WAVE = 200;                /* wavelength ~200px        */
const STROKE = 2.2;
const INK = '#B8141A';

function mulberry32(a) {
  return function () {
    a |= 0; a = a + 0x6D2B79F5 | 0;
    let t = Math.imul(a ^ a >>> 15, 1 | a);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}
const rnd = mulberry32(SEED);
const jit = j => (rnd() * 2 - 1) * j;
const r2 = n => Math.round(n * 100) / 100;

/* the baseline the thread follows. Phase is seeded, so the wobble does not
   start at zero crossing on every build. */
const phase = rnd() * Math.PI * 2;
const baseY = x => BASE + AMP * Math.sin((x / WAVE) * Math.PI * 2 + phase);

/* lay the stitches down the line */
const stitches = [];
let x = 4;
while (x < W - 6) {
  const len = LEN + jit(LEN_J);
  const a = (jit(ANG) * Math.PI) / 180;
  const mx = x + len / 2;
  const my = baseY(mx) + jit(YOFF);
  const hx = (len / 2) * Math.cos(a);
  const hy = (len / 2) * Math.sin(a);
  stitches.push({
    x1: r2(mx - hx), y1: r2(my - hy), x2: r2(mx + hx), y2: r2(my + hy),
    o: r2(0.9 + rnd() * 0.1)                      /* 0.9 to 1 opacity */
  });
  x += len + GAP + jit(GAP_J);
}

/* BACK-STITCH AT BOTH ENDS. A real running stitch is locked off: the thread
   doubles back over the last two stitches so it cannot pull out. Here that
   is the same two segments drawn again, a hair off, which reads as thicker
   and slightly doubled rather than as a second line. */
const back = [];
for (const i of [0, 1, stitches.length - 2, stitches.length - 1]) {
  const s = stitches[i];
  back.push({ x1: s.x1 + 0.5, y1: s.y1 + 0.45, x2: s.x2 + 0.5, y2: s.y2 + 0.45, o: 0.95 });
}

const line = s => `<path d="M${s.x1} ${s.y1}L${s.x2} ${s.y2}" opacity="${s.o}"/>`;
const all = stitches.concat(back).map(line).join('');

/* the knots: where the thread was tied off, so a touch fatter than the thread */
const knots =
  `<circle cx="${r2(2.6)}" cy="${r2(baseY(2.6))}" r="1.9"/>` +
  `<circle cx="${r2(W - 2.6)}" cy="${r2(baseY(W - 2.6))}" r="1.9"/>`;

const svg =
`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" preserveAspectRatio="none">
<!-- Generated by tools/build-stitch.js, seed ${SEED}. Do not hand-edit:
     re-run the script instead, or the stitching stops being reproducible. -->
<defs><filter id="s" x="-1%" y="-50%" width="102%" height="200%">
<feGaussianBlur stdDeviation="0.5"/></filter></defs>
<!-- the fold line above: the crease the two pieces were pressed along -->
<path d="M0 ${r2(BASE - 3.5)}H${W}" fill="none" stroke="${INK}" stroke-width="1" opacity="0.18"/>
<!-- the shadow the thread casts, 1px under it and soft -->
<g fill="none" stroke="rgba(0,0,0,.14)" stroke-width="${STROKE}" stroke-linecap="round"
   filter="url(#s)" transform="translate(0,1)">${all}</g>
<g fill="rgba(0,0,0,.14)" filter="url(#s)" transform="translate(0,1)">${knots}</g>
<!-- the thread -->
<g fill="none" stroke="${INK}" stroke-width="${STROKE}" stroke-linecap="round">${all}</g>
<g fill="${INK}">${knots}</g>
</svg>
`;

const OUT = path.join(ROOT, 'assets/img/stitch.svg');
fs.writeFileSync(OUT, svg);
console.log('wrote assets/img/stitch.svg');
console.log('  seed ' + SEED + ', ' + stitches.length + ' stitches over ' + W + 'px, ' +
  back.length + ' back-stitched, 2 knots');
console.log('  ' + (svg.length / 1024).toFixed(1) + 'KB');
